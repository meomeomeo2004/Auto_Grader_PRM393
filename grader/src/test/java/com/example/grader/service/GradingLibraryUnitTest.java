    /** Dựng thư mục grader-base giả. locateTemplateDir nhận ra nó nhờ Dockerfile.base. */
    private ExamService examVoiPubspec(String ten, String pubspec) throws Exception {
        Path base = Files.createDirectories(thuMuc.resolve(ten));
        Files.writeString(base.resolve("Dockerfile.base"), "FROM scratch\n", StandardCharsets.UTF_8);
        if (pubspec != null) {
            Files.writeString(base.resolve("pubspec.base.yaml"), pubspec, StandardCharsets.UTF_8);
        }
        ExamService svc = new ExamService();
        datField(svc, "templateDir", base.toAbsolutePath().toString());
        return svc;
    }

