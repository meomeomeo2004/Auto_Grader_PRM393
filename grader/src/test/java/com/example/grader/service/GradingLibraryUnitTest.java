    void ut27_utcid01_docCaDevDependencies() throws Exception {
        ExamService svc = examVoiPubspec("base1", PUBSPEC_DU);

        Map<String, Map<String, Object>> rows = theoTen(svc.listManagedPackages());

        assertEquals(Set.of("flutter", "intl", "sqflite", "flutter_test", "flutter_lints"), rows.keySet(),
                "flutter_test nằm ở dev_dependencies — bỏ khối đó là bảng tick thiếu đúng gói mọi bài đều cần");
        assertEquals("(flutter sdk)", rows.get("flutter").get("version"));
        assertEquals("^0.19.0", rows.get("intl").get("version"));
        assertEquals(true, rows.get("flutter").get("protected"));
        assertEquals(true, rows.get("flutter_test").get("protected"));
        assertEquals(true, rows.get("flutter_lints").get("protected"),
                "flutter_lints chỉ để phân tích mã, khoá lại để không ai xoá rồi tưởng đã cấm được gì");
        assertEquals(false, rows.get("intl").get("protected"));
        assertEquals(false, rows.get("sqflite").get("protected"));
    }

