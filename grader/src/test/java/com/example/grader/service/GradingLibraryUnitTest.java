    /** Bộ giá trị hợp lệ suy từ chính giới hạn của máy đang chạy test. */
    private Map<String, Object> than(double cpus, int mem, int con, int timeout) {
        Map<String, Object> b = new LinkedHashMap<>();
        b.put("cpus", cpus);
        b.put("memoryMb", mem);
        b.put("maxConcurrent", con);
        b.put("timeoutSeconds", timeout);
        return b;
    }

    @Test
    @DisplayName("UT30 UTCID01 — giá trị hợp lệ được lưu và áp ngay số worker")
    void ut30_utcid01_giaTriHopLe() {
        // Kẹp vào khoảng của máy đang chạy: giới hạn CPU/RAM phụ thuộc docker info.
        double cpus = Math.min(Math.max(2.0, so("limits", "cpusMin")), so("limits", "cpusMax"));
        int mem = (int) Math.min(Math.max(2048, so("limits", "memoryMbMin")), so("limits", "memoryMbMax"));
        int con = (int) Math.min(Math.max(3, so("limits", "maxConcurrentMin")), so("limits", "maxConcurrentMax"));

        Map<String, Object> ra = cauHinh.update(than(cpus, mem, con, 240), "nguoi-cham");

        @SuppressWarnings("unchecked")
        Map<String, Object> settings = (Map<String, Object>) ra.get("settings");
        assertEquals(cpus, ((Number) settings.get("cpus")).doubleValue());
        assertEquals(mem, ((Number) settings.get("memoryMb")).intValue());
        assertEquals(con, ((Number) settings.get("maxConcurrent")).intValue());
        assertEquals(240, ((Number) settings.get("timeoutSeconds")).intValue());
        assertEquals("nguoi-cham", ra.get("updatedBy"));
        assertEquals(con, soWorkerDaDoi.get(), "số bài song song phải có hiệu lực NGAY");
    }

