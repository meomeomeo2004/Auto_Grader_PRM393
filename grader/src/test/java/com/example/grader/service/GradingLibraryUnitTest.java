    private static Map<String, Map<String, Object>> theoTen(List<Map<String, Object>> rows) {
        Map<String, Map<String, Object>> ra = new LinkedHashMap<>();
        rows.forEach(r -> ra.put(String.valueOf(r.get("name")), r));
        return ra;
    }

