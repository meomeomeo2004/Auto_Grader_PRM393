    @ParameterizedTest(name = "UT30 {0}: {1} lệch biên {2}")
    @MethodSource("ut30_ngoaiKhoang")
    @DisplayName("UT30 — ra ngoài khoảng là NÉM, tuyệt đối không tự cắt gọt cho vừa")
    void ut30_ngoaiKhoangThiNem(String utcid, String truong, int huong, String moDau) {
        Map<String, Object> than = than(so("limits", "cpusMin"), (int) so("limits", "memoryMbMin"),
                (int) so("limits", "maxConcurrentMin"), (int) so("limits", "timeoutSecondsMin"));
        String bien = truong + (huong < 0 ? "Min" : "Max");
        double lech = "cpus".equals(truong) ? 0.5 : 1;
        than.put(truong, so("limits", bien) + huong * lech);

        IllegalArgumentException loi = assertThrows(IllegalArgumentException.class,
                () -> cauHinh.update(than, "nguoi-cham"));

        assertTrue(loi.getMessage().startsWith(moDau),
                utcid + ": lời báo phải nói rõ ô nào sai, đang là: " + loi.getMessage());
    }

